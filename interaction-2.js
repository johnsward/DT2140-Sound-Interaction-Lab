function playAudio() {
    if (!dspNode) {
        return;
    }
    if (audioContext.state === 'suspended') {
        return;
    }

    dspNode.setParamValue("/drop/drop", 1)
    setTimeout(() => { dspNode.setParamValue("/drop/drop", 0) }, 100);
}

