// Phone held in the hand, tilted side to side (roll = rotationY).
// The resting angle is learned from how you hold the phone, so it works even if
// "flat" doesn't read 0°. Each tilt of more than 20° away from rest plays one bubble.
let restY = null;    // learned resting angle
let tilted = false;

function rotationChange(rotx, roty, rotz) {
    if (restY === null) restY = roty;
    const diff = roty - restY;
    if (!tilted && Math.abs(diff) > 20) {
        tilted = true;
        playAudio();
    } else if (tilted && Math.abs(diff) < 10) {   // back near rest: ready for the next tilt
        tilted = false;
    }
    if (!tilted) {
        restY += (roty - restY) * 0.02;          // slowly follow the resting angle
    }
}

